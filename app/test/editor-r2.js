const taskBlocks = text => [{key:text,html:'<ul>'+text.split('\n').map(line=>'<li class="task-list-item"><input class="task-list-item-checkbox" disabled type="checkbox">'+line.slice(6)+'</li>').join('')+'</ul>'}];
const initial = '- [ ] original';
const inserted = '- [ ] inserted\n- [ ] original';
await doc(initial, 'task-revision.md', 30, 'read', taskBlocks(initial));
let finishRender;
window.simplemd.renderBlocks = text => new Promise(resolve => finishRender = () => resolve({title:'tasks',blocks:taskBlocks(text)}));
listeners.disk(inserted, 30);
await until(() => finishRender);
document.querySelector('#doc .task-list-item').click();
await wait(180);
listeners.flush(1);
assert(flushed.text === inserted && !flushed.dirty, 'stale displayed checkbox cannot edit a newer reload while rendering is pending');
finishRender();
await wait(80);

await doc(initial, 'task-lazy-race.md', 31, 'read', taskBlocks(initial));
finishRender = null;
document.querySelector('#doc .task-list-item').click();
listeners.disk(inserted, 31);
await until(() => finishRender);
await wait(150);
listeners.flush(1);
assert(flushed.text === inserted && !flushed.dirty, 'task source identity is rechecked after lazy imports and editor initialization');
finishRender();
await wait(80);
window.simplemd.renderBlocks = async text => ({title:'tasks',blocks:taskBlocks(text)});
document.querySelector('#doc .task-list-item').click();
await wait(150);
listeners.flush(1);
assert(flushed.text === '- [x] inserted\n- [ ] original', 'freshly mounted checkbox edits its corresponding source task');

await window.simplemd.setSettings({autosave:true});
await doc('clean baseline A', 'delayed-accept.md', 32, 'edit');
let accept;
const externalDisk = 'external revision B';
const savesBeforeConflict = pending.length;
window.simplemd.acceptDisk = () => new Promise(resolve => accept = resolve);
listeners.disk(externalDisk, 32);
await until(() => accept);
const source = document.querySelector('#editor-host .cm-content');
source.focus();
document.execCommand('selectAll');
document.execCommand('insertText',false,'local revision C');
await wait(40);
accept(true);
await until(() => !document.querySelector('#banner').hidden);
listeners.transition(true);
listeners.flush(1);
assert(flushed.documentId === 32 && flushed.dirty && flushed.conflict === true && flushed.text === 'local revision C', 'close flush retains unresolved conflict after a clean disk acknowledgement races typing');
listeners.transition(false);
listeners.transition(true);
listeners.flush(2);
assert(flushed.conflict === true && flushed.text === 'local revision C', 'navigation flush retains the same unresolved conflict and local text');
listeners.transition(false);
await wait(1050);
assert(pending.length === savesBeforeConflict, 'renderer submits no autosave while delayed acceptance leaves an unresolved conflict');
listeners.transition(false);
await window.simplemd.setSettings({autosave:false});
await doc('R2 checks complete', 'r2-complete.md', 33, 'read', [{key:'complete',html:'<h1>R2 checks complete</h1>'}]);
