const prefs = document.querySelector('#preferences');
const topbar = document.querySelector('#preferences-btn');
topbar.focus();
topbar.click();
assert(prefs.open && prefs.getAttribute('aria-labelledby') === 'preferences-title', 'topbar opens the labelled native Preferences dialog');
assert(document.querySelector('#pref-shortcut').value === 'Ctrl+Shift+Space', 'global shortcut displays human-readable Ctrl instead of storage terms');
assert(document.activeElement.id === 'pref-theme', 'Preferences starts with its theme control focused');
assert(document.querySelector('#pref-spacePreview').disabled && document.querySelector('#pref-space-note').textContent.includes('unavailable on Linux'), 'unsupported Space preview is disabled and explained');
const choose = async (id, value) => {
 const input = document.getElementById(id);
 input.value = value;
 input.dispatchEvent(new Event('change',{bubbles:true}));
 await wait(50);
};
await choose('pref-theme','dark');
assert(settings.theme === 'dark' && document.documentElement.dataset.theme === 'dark' && getComputedStyle(document.body).backgroundColor === 'rgb(22, 22, 23)', 'Dark preference updates confirmed settings and the rendered palette immediately');
await fixture.screenshot('preferences-dark');
await choose('pref-theme','light');
assert(settings.theme === 'light' && getComputedStyle(document.body).backgroundColor === 'rgb(252, 252, 251)', 'Light preference updates the rendered palette immediately');
await choose('pref-typeface','serif');
await choose('pref-width','wide');
await choose('pref-zoom','125');
assert(settings.typeface === 'serif' && settings.width === 'wide' && settings.zoom === 1.25 && document.documentElement.dataset.typeface === 'serif' && document.querySelector('#pref-zoom-value').value === '125%', 'typeface width and text size patch their existing settings');
await choose('pref-mode','split');
assert(settings.mode === 'split', 'default editing mode updates the existing preference');
for (const key of ['autosave','vim','spellcheck','launchAtLogin']) {
 const input = document.getElementById('pref-'+key);
 const expected = !input.checked;
 input.click();
 await wait(50);
 assert(settings[key] === expected && input.checked === expected, key+' toggle synchronizes through confirmed settings');
}
const saved = {...settings};
await fixture.screenshot('preferences-light');
const existingShortcut = settings.shortcut;
const existingDisplay = document.querySelector('#pref-shortcut').value;
const saveSettings = window.simplemd.setSettings;
window.simplemd.setSettings = async patch => {
 if (patch.shortcut === 'Taken') throw new Error('This shortcut is already in use.');
 return saveSettings(patch);
};
document.querySelector('#pref-shortcut').value = 'Taken';
document.querySelector('#pref-shortcut-apply').click();
await wait(50);
assert(settings.shortcut === existingShortcut && document.querySelector('#pref-shortcut').value === existingDisplay && document.querySelector('#pref-status').textContent.includes('already in use'), 'rejected shortcuts display the error and retain the confirmed binding');
document.querySelector('#pref-shortcut').value = 'Control+Alt+M';
document.querySelector('#pref-shortcut-apply').click();
await wait(50);
assert(settings.shortcut === 'Control+Alt+M' && !document.querySelector('#pref-shortcut').hasAttribute('aria-invalid'), 'valid shortcut is applied through the existing settings API');

listeners.settings({...settings,theme:'dark',mode:'source',autosave:false});
assert(document.querySelector('#pref-theme').value === 'dark' && document.querySelector('#pref-mode').value === 'source' && !document.querySelector('#pref-autosave').checked, 'open Preferences synchronizes changes received from menus or restored settings');
document.querySelector('#pref-done').focus();
await fixture.key('Tab');
await wait(50);
assert(prefs.contains(document.activeElement), 'Tab remains trapped inside the native modal');
await fixture.key('Escape');
await wait(60);
assert(!prefs.open && document.activeElement === topbar, 'Escape closes Preferences and restores opener focus');
assert(document.querySelector('#edit').hidden, 'closing Preferences with Escape leaves the reader unchanged');
await command('preferences');
assert(prefs.open, 'Preferences command opens the same dialog');
document.querySelector('#pref-done').click();
await wait(30);
document.querySelector('#empty-preferences').focus();
document.querySelector('#empty-preferences').click();
assert(prefs.open, 'empty-state Preferences action opens the same dialog');
document.querySelector('#pref-done').click();
await wait(30);
listeners.settings(saved);
await command('preferences');
assert(document.querySelector('#pref-theme').value === saved.theme && document.querySelector('#pref-mode').value === saved.mode && document.querySelector('#pref-zoom').value === String(saved.zoom*100), 'reopening Preferences reflects restored settings without resetting other values');
await fixture.screenshot('preferences-restored');
document.querySelector('#pref-done').click();
