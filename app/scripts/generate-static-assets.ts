import path from "node:path";

// $unslop: generated comments and labels stay plain and specific.
const root = path.join(import.meta.dir, "..");
const katex = path.join(root, "node_modules/katex/dist");
const original = await Bun.file(path.join(katex, "katex.min.css")).text();
const faces = [...original.matchAll(/src:url\(fonts\/([^)]*\.woff2)\) format\("woff2"\)(?:,[^}]+)?/g)];
let katexCss = original;
for (const match of faces) {
  const data = Buffer.from(await Bun.file(path.join(katex, "fonts", match[1]!)).arrayBuffer()).toString("base64");
  katexCss = katexCss.replace(match[0], `src:url(data:font/woff2;base64,${data}) format("woff2")`);
}
if (faces.length !== 20 || /url\((?!data:)/.test(katexCss)) throw new Error("Unexpected KaTeX font stylesheet");
const appCss = await Bun.file(path.join(root, "src/renderer/style.css")).text();
const theme = appCss.slice(0, appCss.indexOf(':root[data-theme="dark"]'));
const prose = appCss.slice(appCss.indexOf(".prose {"), appCss.indexOf("/* Pele colours"));
const staticCss = `${theme}\n${prose}\n
*{box-sizing:border-box}body{margin:0;padding:28px 32px;background:var(--bg);color:var(--fg);font:16px/1.7 var(--sans);-webkit-font-smoothing:antialiased}
.prose{overflow-wrap:anywhere}.prose video{max-width:100%}.prose pre{white-space:pre;overflow-wrap:normal}.code-block[data-lang]::after{display:none}
.mdx-component{border:1px solid var(--rule);border-radius:8px;padding:12px}.mdx-label,.mdx-expression{color:var(--muted);font-family:var(--mono)}
img[data-simplemd-theme="dark"]{display:none}@media(prefers-color-scheme:dark){img[data-simplemd-theme="dark"]{display:revert}img[data-simplemd-theme="light"]{display:none}}
@media(max-width:480px){body{padding:16px}}
`;
await Bun.write(path.join(root, "src/shared/static-assets.ts"), `// Generated by scripts/generate-static-assets.ts from the default theme and KaTeX's MIT-licensed assets.\nexport const staticCss = ${JSON.stringify(staticCss)};\nexport const katexCss = ${JSON.stringify(katexCss)};\n`);
